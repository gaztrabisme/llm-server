# Generate synthetic test images as base64-encoded PNGs using Python
generate_test_images() {
    python3 << 'PYEOF'
import base64
import io
import struct
import zlib
import sys
import json

def create_png(width, height, r, g, b):
    """Create a minimal valid PNG with a solid color, pure stdlib."""
    def chunk(chunk_type, data):
        c = chunk_type + data
        crc = struct.pack('>I', zlib.crc32(c) & 0xffffffff)
        return struct.pack('>I', len(data)) + c + crc

    # PNG signature
    sig = b'\x89PNG\r\n\x1a\n'

    # IHDR
    ihdr_data = struct.pack('>IIBBBBB', width, height, 8, 2, 0, 0, 0)
    ihdr = chunk(b'IHDR', ihdr_data)

    # IDAT — raw pixel data with filter byte 0 per row
    raw_rows = b''
    row_data = bytes([r, g, b]) * width
    for _ in range(height):
        raw_rows += b'\x00' + row_data
    compressed = zlib.compress(raw_rows)
    idat = chunk(b'IDAT', compressed)

    # IEND
    iend = chunk(b'IEND', b'')

    return sig + ihdr + idat + iend

# Generate 224x224 small image (solid blue)
small_png = create_png(224, 224, 70, 130, 230)
small_b64 = base64.b64encode(small_png).decode('ascii')

# Generate 768x768 medium image (solid green gradient approximation — solid for simplicity)
medium_png = create_png(768, 768, 120, 200, 80)
medium_b64 = base64.b64encode(medium_png).decode('ascii')

# Output as JSON
print(json.dumps({
    'small': small_b64,
    'medium': medium_b64
}))
PYEOF
}

if [[ "$DRY_RUN" == true ]]; then
    echo "[DRY RUN] Generate synthetic test images"
    echo "[DRY RUN] Send 3 image requests per size to $SERVER_URL/v1/chat/completions"
    SMALL_PP_TPS=150.0
    MEDIUM_PP_TPS=80.0
else
    log "Generating synthetic test images..."
    IMAGE_DATA=$(generate_test_images)

    SMALL_B64=$(echo "$IMAGE_DATA" | python3 -c "import sys,json; print(json.load(sys.stdin)['small'])")
    MEDIUM_B64=$(echo "$IMAGE_DATA" | python3 -c "import sys,json; print(json.load(sys.stdin)['medium'])")

    log "Small image base64 length: ${#SMALL_B64}"
    log "Medium image base64 length: ${#MEDIUM_B64}"

    # Function to run image PP measurement
    # NOTE: log calls use >&2 to keep stdout clean for return value capture
    measure_image_pp() {
        local label="$1"
        local b64_data="$2"
        local runs=3
        local tps_values=()

        for i in $(seq 1 "$runs"); do
            log "  $label request $i/$runs $([ "$i" -eq 1 ] && echo '(warmup)' || echo '(measured)')..." >&2

            START_MS=$(date +%s%3N)

            # Write base64 to temp file to avoid ARG_MAX limits with large images
            local b64_file
            b64_file=$(mktemp /tmp/vision-eval-b64-XXXXXX.txt)
            echo -n "$b64_data" > "$b64_file"

            # Build and send request via Python, reading base64 from file
            RESPONSE=$(python3 << IMGEOF
import json, sys, urllib.request

with open('$b64_file') as f:
    b64 = f.read()

payload = json.dumps({
    'model': 'qwen3.5',
    'messages': [{
        'role': 'user',
        'content': [
            {
                'type': 'image_url',
                'image_url': {'url': 'data:image/png;base64,' + b64}
            },
            {
                'type': 'text',
                'text': 'Describe this image in detail.'
            }
        ]
    }],
    'max_tokens': 100,
    'temperature': 0.7,
    'stream': False
}).encode('utf-8')

req = urllib.request.Request(
    '$SERVER_URL/v1/chat/completions',
    data=payload,
    headers={'Content-Type': 'application/json'}
)
try:
    with urllib.request.urlopen(req, timeout=120) as resp:
        print(resp.read().decode('utf-8'))
except Exception as e:
    print(json.dumps({'error': str(e)}), file=sys.stderr)
    sys.exit(1)
IMGEOF
            ) || {
                rm -f "$b64_file"
                log "  WARNING: $label request $i failed" >&2
                continue
            }

            rm -f "$b64_file"

            END_MS=$(date +%s%3N)
            WALL_MS=$((END_MS - START_MS))

            # Extract PP speed from timings or estimate
            PP_TPS=$(echo "$RESPONSE" | python3 -c "
import sys, json
try:
    d = json.load(sys.stdin)
    if 'error' in d:
        print(0)
    elif 'timings' in d:
        pp = d['timings'].get('prompt_per_second', 0)
        if pp > 0:
            print(round(pp, 1))
        else:
            # Fall back: prompt_tokens / prompt processing time
            prompt_ms = d['timings'].get('prompt_ms', 0)
            prompt_n = d['timings'].get('prompt_n', 0)
            if prompt_ms > 0 and prompt_n > 0:
                print(round(prompt_n / (prompt_ms / 1000.0), 1))
            else:
                print(0)
    else:
        # Rough estimate from wall clock (not accurate, includes TG time)
        prompt_tok = d.get('usage', {}).get('prompt_tokens', 0)
        comp_tok = d.get('usage', {}).get('completion_tokens', 0)
        if prompt_tok > 0 and $WALL_MS > 0:
            # Estimate: assume TG took comp_tok * (1/74) seconds
            est_tg_s = comp_tok / 74.0
            est_pp_s = ($WALL_MS / 1000.0) - est_tg_s
            if est_pp_s > 0:
                print(round(prompt_tok / est_pp_s, 1))
            else:
                print(0)
        else:
            print(0)
except Exception:
    print(0)
" 2>/dev/null || echo "0")

            PROMPT_TOKENS=$(echo "$RESPONSE" | python3 -c "
import sys, json
try:
    d = json.load(sys.stdin)
    print(d.get('usage', {}).get('prompt_tokens', 0))
except Exception:
    print(0)
" 2>/dev/null || echo "0")

            log "    ${PROMPT_TOKENS} prompt tokens, PP: ${PP_TPS} tok/s, wall: ${WALL_MS}ms" >&2

            # Skip warmup (run 1)
            if [[ "$i" -gt 1 ]]; then
                tps_values+=("$PP_TPS")
            fi
        done

        # Calculate mean of measured runs
        if [[ ${#tps_values[@]} -gt 0 ]]; then
            MEAN_TPS=$(printf '%s\n' "${tps_values[@]}" | python3 -c "
import sys, statistics
vals = [float(line.strip()) for line in sys.stdin if line.strip() and float(line.strip()) > 0]
print(round(statistics.mean(vals), 1) if vals else 0)
" 2>/dev/null || echo "0")
            echo "$MEAN_TPS"
        else
            echo "0"
        fi
    }

    log "Measuring small image (224x224) PP speed..."
    SMALL_PP_TPS=$(measure_image_pp "small_224" "$SMALL_B64")
    log "Small image PP: ${SMALL_PP_TPS} tok/s"
    echo ""

    log "Measuring medium image (768x768) PP speed..."
    MEDIUM_PP_TPS=$(measure_image_pp "medium_768" "$MEDIUM_B64")
    log "Medium image PP: ${MEDIUM_PP_TPS} tok/s"
fi

