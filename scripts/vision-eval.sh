# =============================================================================
# Argument parsing
# =============================================================================

usage() {
    sed -n '2,45p' "$0" | sed 's/^# \?//'
    exit 0
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --limit)
            LIMIT="$2"
            shift 2
            ;;
        --benchmarks)
            BENCHMARKS="$2"
            shift 2
            ;;
        --server-url)
            SERVER_URL="$2"
            shift 2
            ;;
        --skip-server)
            SKIP_SERVER=true
            shift
            ;;
        --dry-run)
            DRY_RUN=true
            shift
            ;;
        --help|-h)
            usage
            ;;
        *)
            echo "Unknown option: $1"
            usage
            ;;
    esac
done

# =============================================================================
# Utility functions
# =============================================================================

log() {
    echo "[$(date +%H:%M:%S)] $*"
}

run_cmd() {
    if [[ "$DRY_RUN" == true ]]; then
        echo "[DRY RUN] $*"
        return 0
    fi
    "$@"
}

# Cleanup function for trap
cleanup() {
    if [[ "$SKIP_SERVER" == false ]]; then
        log "Cleaning up container: $CONTAINER_NAME"
        docker rm -f "$CONTAINER_NAME" > /dev/null 2>&1 || true
    fi
    # Clean up temp files (BENCH_TEMP set later, may be empty)
    [[ -n "${BENCH_TEMP:-}" ]] && rm -f "$BENCH_TEMP"
}

