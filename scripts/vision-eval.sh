TEXT_TG_TPS=0
TEXT_TG_OVERHEAD_PCT=0

if [[ "$DRY_RUN" == true ]]; then
    echo "[DRY RUN] Send 2 text-only requests to $SERVER_URL/v1/chat/completions"
    TEXT_TG_TPS=72.1
    TEXT_TG_OVERHEAD_PCT=-2.6
else
    TEXT_PROMPT="Write a short story about a robot learning to paint. Be creative and detailed. Include vivid descriptions of colors, emotions, and the creative process."

    for i in 1 2; do
        log "Text-only request $i/2 $([ "$i" -eq 1 ] && echo '(warmup)' || echo '(measured)')..."

        START_MS=$(date +%s%3N)

        RESPONSE=$(python3 -c "
import json, urllib.request, sys
payload = json.dumps({
    'model': 'qwen3.5',
    'messages': [{'role': 'user', 'content': '$TEXT_PROMPT'}],
    'max_tokens': 256,
    'temperature': 0.7,
    'stream': False
}).encode('utf-8')
req = urllib.request.Request(
    '$SERVER_URL/v1/chat/completions',
    data=payload,
    headers={'Content-Type': 'application/json'}
)
try:
    with urllib.request.urlopen(req, timeout=120) as resp:
        print(resp.read().decode('utf-8'))
except Exception as e:
    print(json.dumps({'error': str(e)}), file=sys.stderr)
    sys.exit(1)
" 2>/dev/null) || {
            log "WARNING: Text-only request $i failed"
            continue
        }

        END_MS=$(date +%s%3N)
        WALL_MS=$((END_MS - START_MS))

        # Try to extract timings from llama.cpp extended response
        TPS=$(echo "$RESPONSE" | python3 -c "
import sys, json
try:
    d = json.load(sys.stdin)
    # llama.cpp returns timings in the response
    if 'timings' in d:
        print(round(d['timings'].get('predicted_per_second', 0), 1))
    else:
        # Fall back to wall clock calculation
        comp = d.get('usage', {}).get('completion_tokens', 0)
        if comp > 0:
            # Wall time is passed via environment
            wall_s = $WALL_MS / 1000.0
            print(round(comp / wall_s, 1))
        else:
            print(0)
except Exception:
    print(0)
" 2>/dev/null || echo "0")

        COMP_TOKENS=$(echo "$RESPONSE" | python3 -c "
import sys, json
try:
    d = json.load(sys.stdin)
    print(d.get('usage', {}).get('completion_tokens', 0))
except Exception:
    print(0)
" 2>/dev/null || echo "0")

        if [[ "$i" -eq 1 ]]; then
            log "  Warmup: ${COMP_TOKENS} tokens, ${TPS} tok/s, ${WALL_MS}ms"
        else
            TEXT_TG_TPS="$TPS"
            log "  Measured: ${COMP_TOKENS} tokens, ${TPS} tok/s, ${WALL_MS}ms"
        fi
    done

    # Calculate overhead percentage
    if [[ "$TEXT_TG_TPS" != "0" ]]; then
        TEXT_TG_OVERHEAD_PCT=$(python3 -c "
tps = $TEXT_TG_TPS
baseline = $BASELINE_TG_TPS
pct = round(((tps - baseline) / baseline) * 100, 1)
print(pct)
" 2>/dev/null || echo "0")
    fi

    log "TG speed (text-only, with mmproj loaded): ${TEXT_TG_TPS} tok/s (${TEXT_TG_OVERHEAD_PCT}% vs baseline)"
fi

