#!/usr/bin/env bash
# =============================================================================
# vision-eval.sh — Vision quality evaluation for Qwen3.5-35B-A3B
# =============================================================================
#
# Usage:
#   ./vision-eval.sh [options]
#
# Options:
#   --limit <n>       Samples per benchmark (default: 10)
#   --benchmarks <b>  Comma-separated benchmarks (default: ocrbench,mmmu_val,mathvista_testmini,realworldqa,ai2d)
#   --server-url <u>  Server URL (default: http://localhost:8080)
#   --skip-server      Don't start/stop server (assumes already running)
#   --dry-run          Print commands without executing
#   --help             Show this help
#
# Prerequisites:
#   1. Docker image with vision support:
#      docker build --build-arg LLAMA_CPP_REF=b8177 \
#        -t llm-server/llama-cpp:latest-vision \
#        -f docker/Dockerfile.llama-cpp .
#
#   2. lmms-eval installed in a venv:
#      python3 -m venv benchmarks/vision/venv
#      source benchmarks/vision/venv/bin/activate
#      pip install lmms-eval
#
#   3. Model and mmproj files in models/:
#      - Qwen3.5-35B-A3B-Q4_K_M.gguf
#      - mmproj-BF16.gguf
#
# Examples:
#   # Full evaluation (50 samples across 5 benchmarks)
#   ./vision-eval.sh
#
#   # Quick smoke test (5 samples each)
#   ./vision-eval.sh --limit 5
#
#   # Single benchmark
#   ./vision-eval.sh --benchmarks ocrbench --limit 20
#
#   # Against already-running server
#   ./vision-eval.sh --skip-server --server-url http://localhost:8080
#
# =============================================================================
#
# SPEC — Implementation notes for the developer:
#
# 1. SERVER MANAGEMENT
#    - Start server with vision config:
#      docker run -d --gpus all --ipc host \
#        -v models:/models:ro -p 8080:8080 \
#        llm-server/llama-cpp:latest-vision \
#        -m /models/Qwen3.5-35B-A3B-Q4_K_M.gguf \
#        --mmproj /models/mmproj-BF16.gguf \
#        --fit on --fit-target 2000 \
#        -fa on -t 20 --no-mmap --jinja \
#        -ctk q8_0 -ctv q8_0 \
#        -c 32768 \
#        --host 0.0.0.0 --port 8080
#    - Wait for /health (up to 600s)
#    - Capture VRAM after model load (including mmproj overhead)
#    - Note: context reduced to 32k (from 65k) to make room for mmproj in VRAM
#
# 2. VRAM COMPARISON
#    - Before starting vision server: record VRAM baseline
#    - After vision server loaded: record VRAM with mmproj
#    - Calculate delta: mmproj overhead = vision_vram - baseline
#    - Baseline comes from existing benchmarks or a quick no-mmproj startup
#
# 3. SPEED IMPACT MEASUREMENT
#    - Run text-only TG benchmark (2 runs of short_prompt workload)
#    - Compare against production baseline (~74 tok/s)
#    - This measures the overhead of having mmproj loaded even for text
#
# 4. IMAGE PP MEASUREMENT
#    - Send image + text prompt via /v1/chat/completions
#    - Use base64-encoded test images:
#      a) 224x224 small image (synthetic, generated by script)
#      b) 768x768 medium image (synthetic, generated by script)
#    - Extract timings.prompt_per_second for image+text PP speed
#    - 3 runs each, first is warmup
#
# 5. QUALITY EVALUATION (lmms-eval)
#    - Activate venv: source benchmarks/vision/venv/bin/activate
#    - Run lmms-eval:
#      python3 -m lmms_eval \
#        --model openai_compatible \
#        --model_args "base_url=http://localhost:8080/v1" \
#        --tasks <benchmarks> \
#        --limit <limit> \
#        --output_path benchmarks/vision/eval-{timestamp}/
#    - Parse results from output directory
#    - Note: lmms-eval may need specific model name config for Qwen3.5
#
# 6. BENCHMARKS
#    | Benchmark | Task ID | What it tests |
#    |-----------|---------|---------------|
#    | OCRBench | ocrbench | OCR accuracy on natural scenes |
#    | MMMU (val) | mmmu_val | Multi-discipline visual understanding |
#    | MathVista (testmini) | mathvista_testmini | Math + visual reasoning |
#    | RealWorldQA | realworldqa | Real-world visual QA |
#    | AI2D | ai2d | Science diagram understanding |
#
# 7. OUTPUT
#    - Results saved to benchmarks/vision/eval-{timestamp}/
#    - Summary table printed to stdout:
#
#      VISION EVALUATION RESULTS
#      =========================
#      VRAM: 15200 MB (with mmproj) vs 14559 MB (without) = +641 MB overhead
#      TG speed (text-only, with mmproj loaded): 72.1 tok/s (-3.5% vs baseline)
#
#      | Benchmark | Score | Official Qwen3.5 | % of Official | Status |
#      |-----------|-------|-------------------|---------------|--------|
#      | OCRBench | 78.0 | 88.0 | 88.6% | PASS |
#      | MMMU | 52.0 | 64.0 | 81.3% | PASS |
#      | MathVista | 45.0 | 62.0 | 72.6% | PASS |
#      | RealWorldQA | 60.0 | 72.0 | 83.3% | PASS |
#      | AI2D | 70.0 | 82.0 | 85.4% | PASS |
#
#      Pass threshold: > 50% of official score
#      (Low bar because: Q4_K_M quantization + --limit 10 high variance)
#
# 8. ERROR HANDLING
#    - If lmms-eval venv doesn't exist: print setup instructions and exit
#    - If Docker image doesn't exist: print build instructions and exit
#    - If mmproj file missing: print download instructions and exit
#    - If a benchmark fails: continue with remaining benchmarks, mark as FAIL
#    - Always cleanup Docker container on exit (trap)
#
# =============================================================================

